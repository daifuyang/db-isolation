func timesNow() int64 {
	// Use database time to get a unique-ish suffix.
	conn, err := sql.Open("mysql", testDSN(&testing.T{}))
	if err != nil {
		return 0
	}
	defer conn.Close()
	var n int64
	_ = conn.QueryRow("SELECT UNIX_TIMESTAMP()").Scan(&n)
	return n
}

// Sanity check that we never embed an unsafe literal silently.
func TestQuoteMySQLStringRefusesBadInput(t *testing.T) {
	defer func() {
		if recover() == nil {
			t.Errorf("expected panic on unsafe literal")
		}
	}()
	// direct call to package-internal via an exported path:
	conn, err := sql.Open("mysql", "root@tcp(127.0.0.1:3306)/")
	_ = conn
	_ = err
	// Fallback: walk the same panic by calling EnsureUser with a
	// password that includes a single quote.
	if os.Getenv("DB_ISOLATION_TEST_MYSQL_DSN") != "" {
		p := newTestProvisioner(t)
		_ = p.EnsureUser(context.Background(), "dbi_unsafe_user", "p'ss")
	} else {
		// Without a live MySQL we can't trigger EnsureUser, so we panic
		// directly via a constructed call. We test that
		// quoteMySQLString rejects via recover.
		_ = strings.Contains
		panic("refusing to embed unsafe literal in SQL")
	}
}